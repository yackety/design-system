"""Halvo release tool: build dist/, guard the public API, bump the version, tag.

Run from the halvo folder:
  python tools/release.py build                 rebuild dist/ (and tailwind/) at the current version
  python tools/release.py check                 compare the public surface with the last release
  python tools/release.py patch|minor|major     check -> bump -> build -> snapshot -> changelog -> npm pack
                                                -> commit this folder + tag halvo@X.Y.Z
      --no-git    do everything except the commit and tag
  Packages land in ../releases/<name>-<version>.tgz; projects install those (or a registry copy).
      --force     allow a minor/patch even though something public was removed (don't)
  python tools/release.py snapshot              record the current surface as released (first release only)

The public surface (api-surface.json) is: every token name, type style and font family key,
every CSS class and custom property in components/bundle.css, and every function on
window.Halvo (motion, ui). Removing or renaming any of them is a breaking change -> major.
"""
import datetime
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SYSTEM = os.path.basename(ROOT)  # tag prefix: halvo@1.2.0 (one repo, many design systems)
P = lambda *a: os.path.join(ROOT, *a)
FONT_RE = re.compile(r'@import url\("https://fonts\.googleapis\.com/[^"]+"\);\s*')


def read(p):
    return open(P(p), encoding='utf-8').read()


def write(p, s):
    os.makedirs(os.path.dirname(P(p)) or ROOT, exist_ok=True)
    open(P(p), 'w', encoding='utf-8', newline='\n').write(s)


def version():
    return json.loads(read('package.json'))['version']


# ---------------------------------------------------------------- build
def tokens_css():
    t = json.loads(read('tokens.json'))
    themes = [x['id'] for x in t['color']['themes']]
    val = lambda v, th: v if isinstance(v, str) else v.get(th, v.get(themes[0]))
    out = []
    for i, th in enumerate(themes):
        sel = ':root, [data-theme="%s"]' % th if i == 0 else '[data-theme="%s"]' % th
        rows = ['  --%s: %s;' % (c['name'], val(c['value'], th)) for c in t['color']['tokens'] + t.get('shadow', {}).get('tokens', [])]
        out.append(sel + ' {\n' + '\n'.join(rows) + '\n}')
    rows = []
    for fam, body in t.items():
        if fam in ('name', 'version', 'meta', 'color', 'type', 'shadow') or not isinstance(body, dict) or 'tokens' not in body:
            continue
        rows += ['  --%s: %s;' % (c['name'], c['value']) for c in body['tokens']]
    rows += ['  --font-%s: %s;' % (k, v) for k, v in t['type']['families'].items()]
    out.append(':root {\n' + '\n'.join(rows) + '\n}')
    return '\n'.join(out) + '\n'


def sync_bundle_version(v):
    s = read('components/bundle.js')
    s2 = re.sub(r"version: '[^']*'", "version: '%s'" % v, s, count=1)
    if s2 != s:
        write('components/bundle.js', s2)


def build():
    v = version()
    sync_bundle_version(v)
    subprocess.run([sys.executable, '-I', P('tools', 'build_tailwind.py'), ROOT], check=True, stdout=subprocess.DEVNULL)
    banner = lambda what: '/*! Halvo v%s — %s. Generated by tools/release.py; edit the sources, not this file. */\n' % (v, what)
    bundle_css = read('components/bundle.css')
    m = FONT_RE.search(bundle_css)
    font = m.group(0).strip() + '\n' if m else ''
    components = FONT_RE.sub('', bundle_css, count=1)
    toks = tokens_css()
    if os.path.isdir(P('dist')):
        shutil.rmtree(P('dist'))
    write('dist/tokens.css', banner('design tokens (CSS custom properties)') + toks)
    write('dist/components.css', banner('component styles; load after tokens.css; add the font yourself') + components)
    write('dist/halvo.css', banner('font + tokens + components, all in one') + font + '\n' + toks + '\n' + components)
    write('dist/halvo.js', banner('motion kit and UI helpers (window.Halvo)') + read('components/bundle.js'))
    for f in ('halvo.css', 'halvo.preset.js'):
        write('dist/tailwind/' + f, read('tailwind/' + f))
    print('built dist/ for v%s' % v)


# ---------------------------------------------------------------- public surface
JS_SURFACE = r"""
const vm = require('vm'), fs = require('fs');
const noop = () => {};
globalThis.window = globalThis;
globalThis.matchMedia = () => ({ matches: false });
globalThis.document = { addEventListener: noop, querySelectorAll: () => [], documentElement: {} };
vm.runInThisContext(fs.readFileSync(process.argv[1], 'utf8'));
const H = globalThis.Halvo, out = {};
for (const k of Object.keys(H)) out[k] = typeof H[k] === 'object' && H[k] ? Object.keys(H[k]).sort() : typeof H[k];
console.log(JSON.stringify(out));
"""


def surface():
    t = json.loads(read('tokens.json'))
    tokens = []
    for fam, body in t.items():
        if isinstance(body, dict) and isinstance(body.get('tokens'), list):
            tokens += ['%s:%s' % (fam, c['name']) for c in body['tokens']]
    tokens += ['type:%s' % s['name'] for g in t['type']['groups'] for s in g['styles']]
    tokens += ['font:%s' % k for k in t['type']['families']]
    tokens += ['theme:%s' % x['id'] for x in t['color']['themes']]
    css = read('components/bundle.css')
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    css = re.sub(r'url\([^)]*\)', '', css)
    css = re.sub(r'"[^"]*"', '""', css)
    selectors = re.findall(r'(?:^|[;{}])\s*([^;{}]+)\{', css)
    classes = sorted({c for s in selectors if not s.strip().startswith('@') for c in re.findall(r'\.(-?[_a-zA-Z][\w-]*)', s)})
    props = sorted(set(re.findall(r'(?:^|[;{\s])(--[\w-]+)\s*:', css)))
    try:
        js = json.loads(subprocess.run(['node', '-e', JS_SURFACE, P('components', 'bundle.js')], check=True, capture_output=True, text=True).stdout)
    except (OSError, subprocess.CalledProcessError) as e:
        sys.exit('could not read window.Halvo with node: %s' % e)
    api = sorted('%s.%s' % (k, f) for k, v in js.items() if isinstance(v, list) for f in v)
    return {'tokens': sorted(tokens), 'classes': classes, 'cssVars': props, 'js': api}


def diff(old, new):
    removed, added = {}, {}
    for k in new:
        o, n = set(old.get(k, [])), set(new[k])
        if o - n:
            removed[k] = sorted(o - n)
        if n - o:
            added[k] = sorted(n - o)
    return removed, added


def check(verbose=True):
    if not os.path.exists(P('api-surface.json')):
        print('no api-surface.json yet: run `python tools/release.py snapshot` for the first release')
        return {}, {}
    old = json.loads(read('api-surface.json'))
    removed, added = diff(old['surface'], surface())
    if verbose:
        print('last release: v%s' % old['version'])
        for title, d in (('BREAKING - removed or renamed (needs a major)', removed), ('added (minor)', added)):
            if d:
                print('\n' + title)
                for k, v in d.items():
                    print('  %-8s %s' % (k, ', '.join(v)))
        if not removed and not added:
            print('public surface unchanged (patch, or a minor if behaviour/visuals changed)')
    return removed, added


def snapshot():
    write('api-surface.json', json.dumps({'version': version(), 'surface': surface()}, indent=1) + '\n')
    print('recorded public surface for v%s' % version())


# ---------------------------------------------------------------- release
def bump(kind, git=True, force=False):
    removed, added = check()
    if removed and kind != 'major' and not force:
        sys.exit('\nrefusing a %s: public names were removed. Release a major, or keep the old names as deprecated aliases.' % kind)
    if kind == 'patch' and added and not force:
        sys.exit('\nrefusing a patch: new public names were added. Release a minor.')
    cl = read('CHANGELOG.md')
    m = re.search(r'## \[Unreleased\]\n(.*?)(?=\n## \[|\Z)', cl, re.S)
    notes = m.group(1).strip() if m else ''
    if not notes:
        sys.exit('\nCHANGELOG.md has nothing under "## [Unreleased]": describe the change first.')
    major, minor, patch = (int(x) for x in version().split('.'))
    new = {'major': '%d.0.0' % (major + 1), 'minor': '%d.%d.0' % (major, minor + 1), 'patch': '%d.%d.%d' % (major, minor, patch + 1)}[kind]
    pkg = json.loads(read('package.json'))
    pkg['version'] = new
    write('package.json', json.dumps(pkg, indent=2, ensure_ascii=False) + '\n')
    today = datetime.date.today().isoformat()
    cl = cl.replace(m.group(0), '## [Unreleased]\n\n## [%s] — %s\n\n%s\n' % (new, today, notes), 1)
    write('CHANGELOG.md', cl)
    build()
    snapshot()
    tarball = pack()
    if git:
        tag = '%s@%s' % (SYSTEM, new)
        # stage and commit only this design system's folder: the repo holds several systems
        paths = ['.'] + ([os.path.relpath(tarball, ROOT)] if tarball else [])
        subprocess.run(['git', '-C', ROOT, 'add', '-A', '--'] + paths, check=True)
        subprocess.run(['git', '-C', ROOT, 'commit', '-q', '-m', 'release(%s): %s' % (SYSTEM, new), '--'] + paths, check=True)
        subprocess.run(['git', '-C', ROOT, 'tag', '-a', tag, '-m', '%s %s' % (SYSTEM, new)], check=True)
        print('committed and tagged %s' % tag)
    else:
        print('%s %s ready (not committed)' % (SYSTEM, new))
    if tarball:
        print('package: %s' % tarball)


def pack():
    """npm pack this system into <repo>/releases/, the file projects install from (npm can't install a git subfolder)."""
    dest = os.path.join(os.path.dirname(ROOT), 'releases')
    os.makedirs(dest, exist_ok=True)
    try:
        out = subprocess.run('npm pack --silent --pack-destination "%s"' % dest, cwd=ROOT, shell=True, check=True, capture_output=True, text=True).stdout.strip().splitlines()
        return os.path.join(dest, out[-1]) if out else None
    except (OSError, subprocess.CalledProcessError) as e:
        print('npm pack failed (%s): the release is fine, build the package later with `npm pack`' % e)
        return None


if __name__ == '__main__':
    args = sys.argv[1:]
    cmd = args[0] if args else 'check'
    if cmd == 'build':
        build()
    elif cmd == 'check':
        check()
    elif cmd == 'snapshot':
        snapshot()
    elif cmd in ('major', 'minor', 'patch'):
        bump(cmd, git='--no-git' not in args, force='--force' in args)
    else:
        sys.exit(__doc__)
